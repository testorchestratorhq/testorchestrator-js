// Generates src/generated/ from schemas/to-results.v1.json:
//   standalone.ts  the Ajv validator compiled to plain code (no runtime dependency on Ajv)
//   types.ts       TypeScript types of the document
// Run by `npm run generate` (part of `npm run build`). `npm run check:generated` fails when the committed
// output is stale.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv2020 from 'ajv/dist/2020.js'
import standaloneCode from 'ajv/dist/standalone/index.js'
import { compile } from 'json-schema-to-typescript'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const schema = JSON.parse(readFileSync(join(root, 'schemas', 'to-results.v1.json'), 'utf8'))
const outDir = join(root, 'src', 'generated')
const check = process.argv.includes('--check')

// unicode: false - maxLength counts UTF-16 code units, as the server's String.length() does.
const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  allowUnionTypes: true,
  unicode: false,
  code: { source: true, esm: true, lines: true },
})
const validate = ajv.compile(schema)
let code = standaloneCode(ajv, validate)
if (/require\(/.test(code)) {
  throw new Error('standalone validator needs an Ajv runtime helper; adjust the schema or options')
}
code = code
  .replace('export const validate = ', 'export const validateSchema = ')
  .replace(/export default [^;]+;/, '')
const banner = '// GENERATED by scripts/build-generated.mjs from schemas/to-results.v1.json. Do not edit.\n'
const standalone = `${banner}/* eslint-disable */\n// @ts-nocheck\n${code}\n`

const types = await compile(schema, 'ToResultsDocument', {
  bannerComment: banner.trim(),
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { singleQuote: true, semi: false, printWidth: 110, trailingComma: 'all' },
})

const files = { 'standalone.ts': standalone, 'types.ts': types }
let stale = 0
mkdirSync(outDir, { recursive: true })
for (const [name, content] of Object.entries(files)) {
  const path = join(outDir, name)
  let current
  try {
    current = readFileSync(path, 'utf8')
  } catch {
    current = null
  }
  if (current === content) continue
  if (check) {
    console.error(`stale: src/generated/${name} (run npm run generate)`)
    stale++
  } else {
    writeFileSync(path, content)
    console.log(`wrote src/generated/${name}`)
  }
}
if (stale) process.exit(1)
